// Generates app/tokens.css from replica/design/tokens.json.
// Run after any token change: npm run tokens
import { readFileSync, writeFileSync } from "node:fs";

const t = JSON.parse(readFileSync("replica/design/tokens.json", "utf8"));
const lines = ["/* Generated by scripts/tokens.mjs from replica/design/tokens.json. Do not edit. */", "@theme {"];

for (const [k, v] of Object.entries(t.color)) lines.push(`  --color-${k}: ${v};`);
lines.push(`  --font-sans: ${t.font.sans};`, `  --font-mono: ${t.font.mono};`);
for (const [k, v] of Object.entries(t.type)) {
  lines.push(`  --text-${k}: ${v.size / 16}rem;`, `  --text-${k}--line-height: ${v.line / 16}rem;`);
}
for (const [k, v] of Object.entries(t.radius)) lines.push(`  --radius-${k}: ${v}px;`);
for (const [k, v] of Object.entries(t.shadow)) lines.push(`  --shadow-${k}: ${v};`);
lines.push(`  --ease-app: ${t.motion.ease};`);
lines.push("}", "", ":root {");
for (const [k, v] of Object.entries(t.motion)) if (k !== "ease") lines.push(`  --motion-${k}: ${v};`);
for (const [k, v] of Object.entries(t.layout)) lines.push(`  --layout-${k}: ${v}px;`);
lines.push("}", "");

writeFileSync("app/tokens.css", lines.join("\n"));
console.log("tokens: wrote app/tokens.css");
